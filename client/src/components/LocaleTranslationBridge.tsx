const completeArabicToEnglish: Record<string, string> = {
  ...arabicToEnglish,
  ...operationalEnglishDictionary1,
  ...operationalEnglishDictionary2,
  ...operationalEnglishDictionary3,
  ...operationalEnglishDictionary4,
};
const englishToArabic = Object.fromEntries(Object.entries(completeArabicToEnglish).map(([arabic, english]) => [english, arabic]));
const attributeNames = ["aria-label", "title", "placeholder", "alt"];

function replaceStaticCopy(root: ParentNode, dictionary: Record<string, string>) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode as Text);
  textNodes.forEach(node => {
    const current = node.nodeValue ?? "";
    const leadingWhitespace = current.match(/^\s*/)?.[0] ?? "";
    const trailingWhitespace = current.match(/\s*$/)?.[0] ?? "";
    const translation = dictionary[current.trim()];
    if (translation) node.nodeValue = `${leadingWhitespace}${translation}${trailingWhitespace}`;
  });

  if (!(root instanceof Element) && !(root instanceof Document)) return;
  const elements = root instanceof Document
    ? Array.from(root.querySelectorAll<HTMLElement>("*"))
    : [root as HTMLElement, ...Array.from(root.querySelectorAll<HTMLElement>("*"))];
  elements.forEach(element => {
    attributeNames.forEach(attribute => {
      const current = element.getAttribute(attribute);
      const translation = current ? dictionary[current] : undefined;
      if (translation) element.setAttribute(attribute, translation);
    });
  });
}

export default function LocaleTranslationBridge() {
  const { locale } = useLocale();

  useEffect(() => {
    const dictionary = locale === "en" ? completeArabicToEnglish : englishToArabic;
    const translate = () => replaceStaticCopy(document.body, dictionary);
    translate();
    const observer = new MutationObserver(() => translate());
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [locale]);

  return null;
}
